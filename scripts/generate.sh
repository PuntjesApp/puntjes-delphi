#!/bin/sh
set -eu
cd "$(dirname "$0")/.."
M=.mormot/src
mkdir -p .mormot/build/units .mormot/build/bin
fpc -MDelphi -O2 -Sci -v0 -FU.mormot/build/units -FE.mormot/build/bin \
  -Fi$M -Fu$M/core -Fu$M/net -Fu$M/lib -Fu$M/crypt -Fl.mormot/static/x86_64-linux \
  $M/tools/mopenapi/mopenapi.dpr > /dev/null
python3 tools/stable_names.py spec/api.json .mormot/build/api.json
(cd src && ../.mormot/build/bin/mopenapi ../.mormot/build/api.json Puntjes > /dev/null)
HEADER='Generated by mopenapi (mORMot 2.4-stable) - DO NOT MODIFY BY HAND!'
RULER=$(printf "%${#HEADER}s" '' | tr ' ' '-')
for unit in src/puntjes.dto.pas src/puntjes.client.pas; do
  sed -i -E "1,20{s/^  Generated .* via mopenapi - DO NOT MODIFY BY HAND!$/  $HEADER/;s/^  -+$/  $RULER/}" "$unit"
done
python3 tools/optional_bodies.py spec/api.json src/puntjes.client.pas
python3 tools/enum_members.py src/puntjes.dto.pas src/puntjes.client.pas
